"""Exploratory source-only nested leave-one-cell-line-out benchmarks.

DOES NOT validate DTP biology, infer clinical outcomes, use external GEO studies,
or turn a previously inspected source study into independent validation.

Execution, from the repository root:
    python scripts/baseline_models.py --self-test
    python scripts/baseline_models.py --exploratory-only

Input (generated by earlier pipeline):
    data/metadata/evaluation_protocol.json
    data/processed/development/GSE193258_Control_DTP_provisional.tsv.gz
Output (ignored by Git):
    outputs/baselines/fold_predictions.csv
    outputs/baselines/fold_metrics.csv
    outputs/baselines/baseline_summary.json

Preprocessing, feature selection and hyperparameter choice occur INSIDE each
training fold. The 24 samples are from one study and their class labels also
encode treatment-duration differences. All results are EXPLORATORY only.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import json
import math
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROTOCOL = ROOT / "data" / "metadata" / "evaluation_protocol.json"
OUTPUT = ROOT / "outputs" / "baselines"
TARGETS = {"Control": 0, "DTP": 1}
CANDIDATE_K = (100, 500)
CANDIDATE_C = (0.01, 0.1, 1.0)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def import_ml():
    try:
        import numpy as np
        import sklearn
        from sklearn.dummy import DummyClassifier
        from sklearn.feature_selection import SelectKBest, VarianceThreshold, f_classif
        from sklearn.linear_model import LogisticRegression
        from sklearn.metrics import balanced_accuracy_score, confusion_matrix, recall_score
        from sklearn.pipeline import Pipeline
        from sklearn.preprocessing import StandardScaler
        from sklearn.svm import LinearSVC
    except ImportError as exc:
        raise SystemExit(
            "Required packages missing. Run: python -m pip install numpy scikit-learn"
        ) from exc
    return locals()


def load_matrix(path: Path, expected_sha: str, expected_ids: list[str], np):
    if not path.is_file():
        raise FileNotFoundError(f"Input matrix missing: {path}")
    actual = sha256(path)
    if actual != expected_sha:
        raise ValueError(f"Source matrix SHA-256 mismatch: {path}")
    rows = []
    genes = set()
    with gzip.open(path, "rt", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f, delimiter="\t")
        header = next(reader)
        if header[0].strip().lower() != "gene" or header[1:] != expected_ids:
            raise ValueError("Expression column order differs from the frozen 24-GSM protocol")
        if len(set(header[1:])) != len(expected_ids):
            raise ValueError("Duplicate sample columns in expression matrix")
        for row_number, row in enumerate(reader, start=2):
            if len(row) != len(header):
                raise ValueError(f"Malformed matrix row {row_number}")
            if not row[0] or row[0] in genes:
                raise ValueError(f"Empty/duplicate gene identifier at row {row_number}: {row[0]}")
            genes.add(row[0])
            try:
                values = [float(x) for x in row[1:]]
            except ValueError as e:
                raise ValueError(f"Non-numeric expression at row {row_number}") from e
            if not all(math.isfinite(v) for v in values):
                raise ValueError(f"Non-finite expression value at row {row_number}")
            rows.append(values)
    if len(rows) == 0:
        raise ValueError("Empty gene expression matrix")
    X = np.asarray(rows, dtype=np.float64).T
    if X.shape[0] != len(expected_ids):
        raise ValueError("Unexpected sample count")
    return X, len(genes)


def validate_protocol(protocol: dict) -> dict[str, dict]:
    if protocol.get("source_study") != "GSE193258":
        raise ValueError("Only the declared GSE193258 source study is supported")
    if protocol.get("evaluation_plan", {}).get("external_expression_used_in_tuning") is not False:
        raise ValueError("External expression may not be used for tuning")
    if protocol.get("flags", {}).get("cross_study_expression_pooled") is not False:
        raise ValueError("Cross-study matrix pooling was detected")
    labels = protocol["source_gsm_to_label"]
    by_id = {item["gsm"]: item for item in labels}
    if len(labels) != 24 or len(by_id) != 24:
        raise ValueError("Expected exactly 24 unique GSM IDs")
    count = Counter((x["cell_line"], x["state"]) for x in labels)
    if len({x["cell_line"] for x in labels}) != 4 or len(count) != 8 or set(count.values()) != {3}:
        raise ValueError("Expected four cell lines with 3 Control + 3 DTP each")
    if len(protocol["outer_folds"]) != 4:
        raise ValueError("Expected exactly four outer LOCO folds")
    seen_test_ids = set()
    seen_test_lines = set()
    all_ids = set(by_id)
    for fold in protocol["outer_folds"]:
        line = fold["held_out_cell_line"]
        train, test = set(fold["train_gsm"]), set(fold["test_gsm"])
        if line in seen_test_lines or len(train) != 18 or len(test) != 6:
            raise ValueError("Invalid or duplicate outer holdout")
        seen_test_lines.add(line)
        if train & test or train | test != all_ids or any(by_id[i]["cell_line"] != line for i in test):
            raise ValueError("Outer fold has leakage or wrong held-out cell line")
        seen_test_ids.update(test)
        if len(fold["inner_loco"]) != 3:
            raise ValueError("Each outer fold needs exactly three inner LOCO folds")
        seen_inner = set()
        for inner in fold["inner_loco"]:
            inner_line = inner["held_out_training_cell_line"]
            a, b = set(inner["train_gsm"]), set(inner["validation_gsm"])
            if len(a) != 12 or len(b) != 6 or a & b or a | b != train:
                raise ValueError("Inner fold leakage or invalid sample membership")
            if any(by_id[i]["cell_line"] != inner_line for i in b):
                raise ValueError("Wrong inner validation cell line")
            seen_inner.add(inner_line)
        if seen_inner != {by_id[x]["cell_line"] for x in train}:
            raise ValueError("Inner LOCO is not exhaustive")
    if seen_test_ids != all_ids or len(seen_test_lines) != 4:
        raise ValueError("Some samples were not tested exactly once")
    return by_id


def model_pipeline(model_name: str, k: int, C: float, ml):
    # These steps are fitted fresh in each inner/outer training split.
    model = (ml["LogisticRegression"](C=C, class_weight="balanced", max_iter=2000,
                                      solver="liblinear", random_state=0)
             if model_name == "LogisticRegression"
             else ml["LinearSVC"](C=C, class_weight="balanced", max_iter=4000,
                                   dual=True, random_state=0))
    return ml["Pipeline"]([
        ("variance", ml["VarianceThreshold"]()),
        ("anova", ml["SelectKBest"](score_func=ml["f_classif"], k=k)),
        ("scale", ml["StandardScaler"]()),
        ("classifier", model),
    ])


def score_predictions(y_true, y_pred, ml):
    cm = ml["confusion_matrix"](y_true, y_pred, labels=[0, 1])
    return {
        "balanced_accuracy": float(ml["balanced_accuracy_score"](y_true, y_pred)),
        "control_recall": float(ml["recall_score"](y_true, y_pred, labels=[0, 1],
                                                   pos_label=0, zero_division=0)),
        "dtp_recall": float(ml["recall_score"](y_true, y_pred, labels=[0, 1],
                                               pos_label=1, zero_division=0)),
        "tn": int(cm[0, 0]), "fp": int(cm[0, 1]),
        "fn": int(cm[1, 0]), "tp": int(cm[1, 1]),
    }


def analyze(protocol: dict, X, ml):
    by_id = validate_protocol(protocol)
    ids = [x["gsm"] for x in protocol["source_gsm_to_label"]]
    idx = {s: i for i, s in enumerate(ids)}
    y = ml["np"].array([TARGETS[by_id[s]["state"]] for s in ids])
    predictions = []
    per_fold = []
    tuning = []
    for fold in protocol["outer_folds"]:
        line = fold["held_out_cell_line"]
        outer_train = [idx[s] for s in fold["train_gsm"]]
        outer_test = [idx[s] for s in fold["test_gsm"]]
        for model_name in ("DummyMostFrequent", "LogisticRegression", "LinearSVC"):
            best = None
            if model_name == "DummyMostFrequent":
                estimator = ml["DummyClassifier"](strategy="most_frequent")
                parameters = {"k": None, "C": None}
                best_score = None
            else:
                options = []
                for k in CANDIDATE_K:
                    for C in CANDIDATE_C:
                        scores = []
                        for inner in fold["inner_loco"]:
                            tr = [idx[s] for s in inner["train_gsm"]]
                            va = [idx[s] for s in inner["validation_gsm"]]
                            estimator_inner = model_pipeline(model_name, k, C, ml)
                            estimator_inner.fit(X[tr], y[tr])
                            inner_pred = estimator_inner.predict(X[va])
                            scores.append(float(ml["balanced_accuracy_score"](y[va], inner_pred)))
                        options.append((sum(scores) / len(scores), k, C, scores))
                # Highest validation score; ties resolve to fewer genes and smaller C.
                options.sort(key=lambda x: (-x[0], x[1], x[2]))
                best_score, best_k, best_C, inner_scores = options[0]
                parameters = {"k": int(best_k), "C": float(best_C)}
                estimator = model_pipeline(model_name, best_k, best_C, ml)
                tuning.append({
                    "held_out_cell_line": line, "model": model_name,
                    "chosen_k": best_k, "chosen_C": best_C,
                    "mean_inner_balanced_accuracy": best_score,
                    "inner_balanced_accuracies": inner_scores,
                })
            estimator.fit(X[outer_train], y[outer_train])
            predicted = estimator.predict(X[outer_test]).tolist()
            metrics = score_predictions(y[outer_test], predicted, ml)
            per_fold.append({
                "held_out_cell_line": line, "model": model_name,
                "n_train": len(outer_train), "n_test": len(outer_test),
                "chosen_k": parameters["k"], "chosen_C": parameters["C"],
                "inner_balanced_accuracy": best_score,
                **metrics,
            })
            for index, prediction in zip(outer_test, predicted):
                predictions.append({
                    "held_out_cell_line": line, "model": model_name,
                    "gsm": ids[index], "true_state": by_id[ids[index]]["state"],
                    "predicted_state": "DTP" if prediction else "Control",
                    "correct": int(int(prediction) == int(y[index])),
                })
    summary = {}
    for model in ("DummyMostFrequent", "LogisticRegression", "LinearSVC"):
        p = [v for v in predictions if v["model"] == model]
        if len(p) != 24 or len({v["gsm"] for v in p}) != 24:
            raise ValueError("Each model must predict every GSM exactly once")
        true = [TARGETS[v["true_state"]] for v in p]
        predicted = [TARGETS[v["predicted_state"]] for v in p]
        summary[model] = {
            "mean_outer_balanced_accuracy": sum(v["balanced_accuracy"] for v in per_fold if v["model"] == model) / 4,
            "pooled_holdout": score_predictions(true, predicted, ml),
            "held_out_lines": [v for v in per_fold if v["model"] == model],
        }
    return predictions, per_fold, tuning, summary


def write_csv(path: Path, data: list[dict]):
    if not data:
        raise ValueError("Cannot write empty table")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(data[0]))
        writer.writeheader()
        writer.writerows(data)


def self_test():
    ml = import_ml()
    np = ml["np"]
    source = json.loads(PROTOCOL.read_text(encoding="utf-8")) if PROTOCOL.exists() else None
    if source is not None:
        by_id = validate_protocol(source)
        assert len(by_id) == 24
        assert source["source_gene_count"] == 19712
    # Synthetic fixture tests label ordering, single-test-per-GSM, and isolated fitting.
    ids = [f"GSM{i}" for i in range(24)]
    lines = ["A", "B", "C", "D"]
    rows = [{"gsm": s, "cell_line": lines[i // 6],
             "state": "Control" if i % 6 < 3 else "DTP"} for i, s in enumerate(ids)]
    fake = {
        "source_study": "GSE193258",
        "source_gsm_to_label": rows,
        "evaluation_plan": {"external_expression_used_in_tuning": False},
        "flags": {"cross_study_expression_pooled": False},
        "outer_folds": [],
    }
    for i, line in enumerate(lines):
        tr = [s for j, s in enumerate(ids) if lines[j // 6] != line]
        te = [s for j, s in enumerate(ids) if lines[j // 6] == line]
        inner = []
        for inner_line in lines:
            if inner_line == line:
                continue
            va = [s for j, s in enumerate(ids) if lines[j // 6] == inner_line]
            inner.append({"held_out_training_cell_line": inner_line,
                          "train_gsm": [s for s in tr if s not in va], "validation_gsm": va})
        fake["outer_folds"].append({"held_out_cell_line": line,
                                    "train_gsm": tr, "test_gsm": te, "inner_loco": inner})
    rng = np.random.default_rng(42)
    X = rng.normal(size=(24, 600))
    X[:, :5] += np.array([0 if i % 6 < 3 else 1 for i in range(24)])[:, None] * 0.5
    p, folds, t, s = analyze(fake, X, ml)
    assert len(p) == 72 and len(folds) == 12 and len(t) == 8
    assert all(len([r for r in p if r["model"] == m]) == 24 for m in s)
    # Verify strict rejection of train/test overlap.
    fake["outer_folds"][0]["train_gsm"][0] = fake["outer_folds"][0]["test_gsm"][0]
    try:
        validate_protocol(fake)
        raise AssertionError("Sample leakage was not rejected")
    except ValueError:
        pass
    print("SELF-TEST PASSED (nested LOCO, independent inner tuning, no GSM leakage)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--exploratory-only", action="store_true",
                        help="Explicit acknowledgement: preliminary, NOT publication-grade validation")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return 0
    if not args.exploratory_only:
        parser.error("Only explicitly exploratory benchmarking is allowed; add --exploratory-only")
    if not PROTOCOL.is_file():
        parser.error(f"Missing protocol: {PROTOCOL}")
    protocol = json.loads(PROTOCOL.read_text(encoding="utf-8"))
    validate_protocol(protocol)
    source_rel = Path(protocol["source_matrix"].replace("\\", "/"))
    if source_rel.is_absolute() or ".." in source_rel.parts or source_rel.parts[:3] != ("data", "processed", "development"):
        parser.error("Unsafe or unexpected source matrix path")
    input_matrix = ROOT / source_rel
    ml = import_ml()
    ids = [r["gsm"] for r in protocol["source_gsm_to_label"]]
    X, n_genes = load_matrix(input_matrix, protocol["source_matrix_sha256"], ids, ml["np"])
    if n_genes != int(protocol["source_gene_count"]):
        raise ValueError("Gene count differs from frozen protocol")
    predictions, folds, tuning, metrics = analyze(protocol, X, ml)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    write_csv(OUTPUT / "fold_predictions.csv", predictions)
    write_csv(OUTPUT / "fold_metrics.csv", folds)
    report = {
        "status": "EXPLORATORY_NOT_CONFIRMATORY",
        "analysis": "Observed-state classification in source GSE193258, Control vs DTP",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_matrix": str(source_rel),
        "source_sha256": sha256(input_matrix),
        "protocol_fingerprint": protocol["fingerprint_sha256"],
        "scikit_learn_version": ml["sklearn"].__version__,
        "numpy_version": ml["np"].__version__,
        "samples": int(X.shape[0]), "features_source_only": int(X.shape[1]),
        "outer_folds": 4, "inner_folds_per_outer": 3,
        "models": metrics, "tuning": tuning,
        "limits": [
            "Source study was previously inspected; results are exploratory, not independent validation.",
            "Control vs 21-day DTP labels also encode treatment time, dose and culture conditions.",
            "Models did not receive data from external GEO studies at any stage.",
            "Feature selection, scaling and hyperparameters were fitted only within each training split.",
            "Small folds (3 examples per class) give highly uncertain performance estimates.",
            "Biological identity remains pending independent source-supported review.",
        ],
    }
    (OUTPUT / "baseline_summary.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print("Saved outputs/baselines/fold_predictions.csv, fold_metrics.csv, baseline_summary.json")
    for name, value in metrics.items():
        print(f"{name}: outer mean balanced accuracy={value['mean_outer_balanced_accuracy']:.3f}; "
              f"pooled DTP recall={value['pooled_holdout']['dtp_recall']:.3f}")
    print("EXPLORATORY ONLY — no biological approval or independent external validation")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
